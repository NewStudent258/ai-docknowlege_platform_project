_CN_NUM = "零一二三四五六七八九十"


def cn_article(n: int) -> str:
    """条号转中文（第一条 / 第十二条 / 第二十三条）"""
    if n <= 10:
        return _CN_NUM[n]
    if n < 20:
        return "十" + (_CN_NUM[n - 10] if n > 10 else "")
    return _CN_NUM[n // 10] + "十" + (_CN_NUM[n % 10] if n % 10 else "")


def render_doc(title: str, purpose: str, scope: str, owner: str,
               sections: list[tuple[str, str]]) -> str:
    """将文档定义渲染为 txt 正文，全文条号连续编号"""
    lines = [f"{title}", ""]
    art = 0

    def article(text: str) -> str:
        nonlocal art
        art += 1
        return f"第{cn_article(art)}条 {text}"

    # 第一章 总则（统一结构，内容按文档定制）
    lines += [
        "第一章 总则",
        article(f"为{purpose}，根据国家相关法律法规并结合公司实际情况，制定本制度。"),
        article(f"本制度适用于{scope}。"),
        article(f"{owner}是本制度的归口管理部门，负责本制度的制定、修订、解释与监督执行；"
                 f"各部门负责人负责在本部门范围内组织实施。"),
        "",
    ]

    # 主体章节
    for sec_title, body in sections:
        lines += [sec_title, article(body), ""]

    # 附则（统一收尾）
    lines += [
        "附则",
        article("本制度未尽事宜，按照国家有关法律法规及公司其他相关规定执行。"),
        article(f"本制度由{owner}负责解释。"),
        article("本制度自发布之日起施行，此前公司发布的相关规定与本制度不一致的，以本制度为准。"),
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    out_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else Path("resources/policy_docs")
    out_dir.mkdir(parents=True, exist_ok=True)

    for i, (title, cat, purpose, scope, owner, sections) in enumerate(DOCS, 1):
        safe = title.replace("/", "_").replace("\\", "_")
        fname = f"{i:03d}_{safe}.txt"
        (out_dir / fname).write_text(
            render_doc(title, purpose, scope, owner, sections), encoding="utf-8"
        )

    total_chars = sum(len(f.read_text(encoding="utf-8")) for f in out_dir.glob("*.txt"))
    print(f"已生成 {len(DOCS)} 份文档 -> {out_dir.resolve()}")
    print(f"总字符数：{total_chars:,}")


if __name__ == "__main__":
    main()
